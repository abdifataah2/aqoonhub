import 'dotenv/config';
import assert from 'node:assert/strict';
import bcrypt from 'bcryptjs';
import ExcelJS from 'exceljs';
import {randomUUID} from 'node:crypto';
import {pool} from './db.js';

const origin=process.env.API_ORIGIN||'http://localhost:4000';
const suffix=randomUUID().slice(0,8);
const a='ci-a-'+suffix,b='ci-b-'+suffix;
const password='test-password-very-long';
const hash=await bcrypt.hash(password,10);
let schoolA,schoolB,schoolC;
const call=async(path,body,token)=>{
 const res=await fetch(origin+path,{method:'POST',headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:JSON.stringify(body)});
 return {status:res.status,data:await res.json()};
};
try{
 const created=await pool.query("INSERT INTO schools(slug,name) VALUES($1,'Test A'),($2,'Test B') RETURNING id,slug",[a,b]);
 schoolA=created.rows.find(x=>x.slug===a).id;schoolB=created.rows.find(x=>x.slug===b).id;
 const user=(await pool.query("INSERT INTO users(email,password_hash,full_name) VALUES($1,$2,'Test Admin') RETURNING id",['ci-'+suffix+'@example.test',hash])).rows[0];
 await pool.query("INSERT INTO school_memberships(school_id,user_id,role) VALUES($1,$2,'school_admin')",[schoolA,user.id]);
 const platformUser=(await pool.query("INSERT INTO users(email,password_hash,full_name,is_platform_admin) VALUES($1,$2,'Platform Tester',true) RETURNING id",['platform-'+suffix+'@example.test',hash])).rows[0];
 const platformLogin=await call('/api/platform/login',{email:'platform-'+suffix+'@example.test',password});
 assert.equal(platformLogin.status,200,'platform login works');
 const deniedSchool=await call('/api/platform/schools',{name:'Blocked School',slug:'blocked-'+suffix,adminName:'Blocked',adminEmail:'blocked-'+suffix+'@example.test',adminPassword:password});
 assert.equal(deniedSchool.status,401,'public cannot create schools');
 const createdSchool=await call('/api/platform/schools',{name:'Test C',slug:'ci-c-'+suffix,adminName:'School C Admin',adminEmail:'ci-c-admin-'+suffix+'@example.test',adminPassword:password},platformLogin.data.token);
 assert.equal(createdSchool.status,201,'platform admin creates school');
 schoolC=createdSchool.data.school.id;
 const schoolCLogin=await call('/api/schools/ci-c-'+suffix+'/login',{email:'ci-c-admin-'+suffix+'@example.test',password});
 assert.equal(schoolCLogin.status,200,'new school admin can login');
 const login=await call('/api/schools/'+a+'/login',{email:'ci-'+suffix+'@example.test',password});
 assert.equal(login.status,200,'valid credentials should login');
 const token=login.data.token;
 assert.ok(token);
 const invalid=await call('/api/schools/'+a+'/login',{email:'ci-'+suffix+'@example.test',password:'incorrect'});
 assert.equal(invalid.status,401,'wrong password must be rejected');
 const other=await fetch(origin+'/api/schools/'+b+'/admin/summary',{headers:{Authorization:'Bearer '+token}});
 assert.equal(other.status,403,'tenant A token must not access tenant B');
 const own=await fetch(origin+'/api/schools/'+a+'/admin/summary',{headers:{Authorization:'Bearer '+token}});
 assert.equal(own.status,200,'school admin should access own school');
 const klass=await call('/api/schools/'+a+'/admin/classes',{name:'Class 1',academicYear:'2026'},token);
 assert.equal(klass.status,201);
 const foreign=await fetch(origin+'/api/schools/'+b+'/admin/classes',{headers:{Authorization:'Bearer '+token}});
 assert.equal(foreign.status,403);
 const ownClasses=await fetch(origin+'/api/schools/'+a+'/admin/classes',{headers:{Authorization:'Bearer '+token}});
 assert.equal(ownClasses.status,200);
 assert.ok((await ownClasses.json()).classes.some(x=>x.id===klass.data.class.id));

 const staff=await call('/api/schools/'+a+'/admin/staff',{email:'staff-'+suffix+'@example.test',fullName:'Test Teacher',password,role:'teacher'},token);
 assert.equal(staff.status,201,'admin should create teacher');
 const staffLogin=await call('/api/schools/'+a+'/login',{email:'staff-'+suffix+'@example.test',password});
 assert.equal(staffLogin.status,200,'teacher can login');
 const forbidden=await call('/api/schools/'+a+'/admin/classes',{name:'Forbidden',academicYear:'2026'},staffLogin.data.token);
 assert.equal(forbidden.status,403,'teacher must not create classes');
 const deactivate=await fetch(origin+'/api/schools/'+a+'/admin/staff/'+staff.data.staff.id,{method:'PATCH',headers:{'Content-Type':'application/json',Authorization:'Bearer '+token},body:JSON.stringify({isActive:false})});
 assert.equal(deactivate.status,200,'admin can deactivate staff');
 const revoked=await fetch(origin+'/api/schools/'+a+'/admin/summary',{headers:{Authorization:'Bearer '+staffLogin.data.token}});
 assert.equal(revoked.status,403,'deactivated staff token must be denied');

 const teacherWb=new ExcelJS.Workbook();const teacherWs=teacherWb.addWorksheet('Teachers');
 teacherWs.addRow(['fullName','email','password']);teacherWs.addRow(['Excel Teacher','excel-'+suffix+'@example.test',password]);
 const teacherUpload=await fetch(origin+'/api/schools/'+a+'/admin/staff/import.xlsx',{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'},body:Buffer.from(await teacherWb.xlsx.writeBuffer())});
 assert.equal(teacherUpload.status,201,'Excel teacher import succeeds');
 assert.equal((await teacherUpload.json()).added,1);
 const excelTeacherLogin=await call('/api/schools/'+a+'/login',{email:'excel-'+suffix+'@example.test',password});
 assert.equal(excelTeacherLogin.status,200,'imported teacher can login');
 const student=await call('/api/schools/'+a+'/admin/students',{classId:klass.data.class.id,registrationNumber:'REG-'+suffix,fullName:'Test Student',resultPin:'12345678'},token);
 assert.equal(student.status,201,'student registration should work');
 const subject=await call('/api/schools/'+a+'/admin/subjects',{name:'Math'},token);
 assert.equal(subject.status,201);
 const mapping=await call('/api/schools/'+a+'/admin/class-subjects',{classId:klass.data.class.id,subjectId:subject.data.subject.id},token);
 assert.equal(mapping.status,201,'class subject assignment works');
 const imported=await call('/api/schools/'+a+'/admin/students/import',{students:[{classId:klass.data.class.id,registrationNumber:'BULK-'+suffix,fullName:'Imported Student'}]},token);
 assert.equal(imported.status,201,'bulk import works');
 const studentLogin=await call('/api/schools/'+a+'/student-login',{registrationNumber:'BULK-'+suffix});
 assert.equal(studentLogin.status,200,'registration-only access works');
 const exam=await call('/api/schools/'+a+'/admin/exams',{classId:klass.data.class.id,title:'Final '+suffix,academicYear:'2026'},token);
 assert.equal(exam.status,201,'create exam');
 const mark=await call('/api/schools/'+a+'/admin/exams/'+exam.data.exam.id+'/marks',{studentId:student.data.student.id,subjectId:subject.data.subject.id,score:85,maxScore:100},token);
 assert.equal(mark.status,200,'record exam mark');
 const markWb=new ExcelJS.Workbook();const markWs=markWb.addWorksheet('Marks');
 markWs.addRow(['registrationNumber','subject','score','maxScore']);
 markWs.addRow(['REG-'+suffix,'Math',90,100]);
 const marksUpload=await fetch(origin+'/api/schools/'+a+'/admin/exams/'+exam.data.exam.id+'/marks/import.xlsx',{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'},body:Buffer.from(await markWb.xlsx.writeBuffer())});
 assert.equal(marksUpload.status,201,'Excel marks import succeeds');
 assert.equal((await marksUpload.json()).imported,1);
 const submit=await call('/api/schools/'+a+'/admin/exams/'+exam.data.exam.id+'/submit',{},token);
 assert.equal(submit.status,200,'submit exam');
 const publish=await call('/api/schools/'+a+'/admin/exams/'+exam.data.exam.id+'/publish',{},token);
 assert.equal(publish.status,200,'publish exam');
 const publishedResult=await call('/api/schools/'+a+'/student-login',{registrationNumber:'REG-'+suffix});
 assert.equal(publishedResult.status,200,'student results lookup');
 assert.ok(publishedResult.data.exams.some(e=>e.marks.some(m=>m.subject==='Math'&&m.score===90)),'student sees published marks');
 const crossSchoolResult=await call('/api/schools/'+b+'/student-login',{registrationNumber:'REG-'+suffix});
 assert.equal(crossSchoolResult.status,404,'other school cannot expose student results');
 const attendance=await call('/api/schools/'+a+'/admin/attendance',{studentId:student.data.student.id,date:'2026-10-17',status:'present'},token);
 assert.equal(attendance.status,200,'attendance should be recorded');
 const attendanceList=await fetch(origin+'/api/schools/'+a+'/admin/attendance?date=2026-10-17',{headers:{Authorization:'Bearer '+token}});
 assert.equal(attendanceList.status,200);
 assert.ok((await attendanceList.json()).attendance.some(x=>x.student_id===student.data.student.id));
 const fee=await call('/api/schools/'+a+'/admin/fees',{studentId:student.data.student.id,amount:20,currency:'USD',reference:'TEST-'+suffix,paidOn:'2026-10-17'},token);
 assert.equal(fee.status,201,'payment should be recorded');
 const fees=await fetch(origin+'/api/schools/'+a+'/admin/fees',{headers:{Authorization:'Bearer '+token}});
 assert.equal(fees.status,200);
 assert.ok((await fees.json()).payments.some(x=>x.id===fee.data.payment.id));
 const audit=await fetch(origin+'/api/schools/'+a+'/admin/audit',{headers:{Authorization:'Bearer '+token}});
 assert.equal(audit.status,200);
 assert.ok((await audit.json()).events.some(x=>x.entity_type==='students'),'student changes should be audited');
 console.log('Login, tenant isolation, staff, attendance, payments and audit checks passed');
}finally{
 if(schoolA)await pool.query('DELETE FROM schools WHERE id=$1',[schoolA]);
 if(schoolB)await pool.query('DELETE FROM schools WHERE id=$1',[schoolB]);
 if(schoolC)await pool.query('DELETE FROM schools WHERE id=$1',[schoolC]);
 await pool.query('DELETE FROM users WHERE email=ANY($1)',[['ci-'+suffix+'@example.test','staff-'+suffix+'@example.test','platform-'+suffix+'@example.test','ci-c-admin-'+suffix+'@example.test','excel-'+suffix+'@example.test']]);
 await pool.end();
}
